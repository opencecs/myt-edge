/* Host checks for the grubenv codec: the per-slot kernel keys must round
 * trip, the legacy single key must survive untouched, and hostile or
 * oversized values must be refused. Built by board/Makefile (compilation
 * only there; run the binary manually or from CI). */
#include "y4_grubenv.h"
#include <errno.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

static int failures;

static void check(int ok, const char *what) {
  if (!ok) {
    failures++;
    fprintf(stderr, "FAIL: %s\n", what);
  }
}

static void parse_block(const unsigned char *block, struct y4_slot_state *state) {
  check(y4_grubenv_parse(block, state) == 0, "parse succeeds");
}

int main(void) {
  unsigned char block[Y4_GRUBENV_BYTES];
  struct y4_slot_state state;

  /* The factory block layout: per-slot keys, no legacy key. */
  memset(&state, 0, sizeof state);
  state.have_default = 1; state.default_entry = 1;
  state.have_slot = 1; state.slot[0] = 'B';
  state.have_boot_kernel_a = 1;
  strcpy(state.boot_kernel_a, "20261112-r184");
  state.have_boot_kernel_b = 1;
  strcpy(state.boot_kernel_b, "20261113-r201");
  state.boot_count = 2; state.boot_ok = 0;
  check(y4_grubenv_render(&state, block) == 0, "render factory block");
  check(memcmp(block, "# GRUB Environment Block\n", 25) == 0, "grub signature kept");
  check(block[Y4_GRUBENV_BYTES - 1] == '#', "'#' padding terminator");
  {
    struct y4_slot_state parsed;
    memset(&parsed, 0, sizeof parsed);
    parse_block(block, &parsed);
    check(parsed.have_default == 1 && parsed.default_entry == 1, "default round trip");
    check(parsed.have_slot == 1 && parsed.slot[0] == 'B', "slot round trip");
    check(parsed.have_boot_kernel_a == 1 &&
          !strcmp(parsed.boot_kernel_a, "20261112-r184"), "boot_kernel_a round trip");
    check(parsed.have_boot_kernel_b == 1 &&
          !strcmp(parsed.boot_kernel_b, "20261113-r201"), "boot_kernel_b round trip");
    check(parsed.have_boot_kernel == 0, "legacy key absent when unset");
    check(parsed.boot_count == 2 && parsed.boot_ok == 0, "counters round trip");

    /* A slot update (boot_count bump) must preserve the other slot's
     * binding: the exact rollback-safety property. */
    parsed.boot_count = 3;
    check(y4_grubenv_render(&parsed, block) == 0, "render updated block");
    char *a = strstr((char *)block, "boot_kernel_a=20261112-r184\n");
    char *b = strstr((char *)block, "boot_kernel_b=20261113-r201\n");
    check(a && b, "both slot bindings survive an update");
    check(strstr((char *)block, "boot_count=3\n") != NULL, "count update rendered");
  }

  /* A legacy block (old factory image): single key only. */
  {
    const char *legacy =
        "# GRUB Environment Block\n"
        "# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"
        "default=0\nslot=A\nboot_kernel=6.6.89-cix-build-generic\n"
        "boot_count=0\nboot_ok=1\n";
    unsigned char raw[Y4_GRUBENV_BYTES];
    memset(raw, '#', sizeof raw);
    memcpy(raw, legacy, strlen(legacy));
    struct y4_slot_state parsed;
    memset(&parsed, 0, sizeof parsed);
    parse_block(raw, &parsed);
    check(parsed.have_boot_kernel == 1 &&
          !strcmp(parsed.boot_kernel, "6.6.89-cix-build-generic"),
          "legacy key parsed");
    check(parsed.have_boot_kernel_a == 0 && parsed.have_boot_kernel_b == 0,
          "no per-slot keys invented");
    /* Round trip must re-emit the legacy key unchanged: an old grub.cfg
     * keeps reading it. */
    check(y4_grubenv_render(&parsed, block) == 0, "render legacy block");
    check(strstr((char *)block, "boot_kernel=6.6.89-cix-build-generic\n") != NULL,
          "legacy key preserved");
    check(strstr((char *)block, "boot_kernel_a=") == NULL,
          "no per-slot keys written for a legacy board");
  }

  /* Legacy key and per-slot keys coexist (rootfs-only OTA on a new board
   * whose grubenv still carries the legacy key). */
  {
    struct y4_slot_state mixed;
    memset(&mixed, 0, sizeof mixed);
    mixed.have_default = 1; mixed.default_entry = 0;
    mixed.have_slot = 1; mixed.slot[0] = 'A';
    mixed.have_boot_kernel = 1;
    strcpy(mixed.boot_kernel, "6.6.89-cix-build-generic");
    mixed.have_boot_kernel_a = 1;
    strcpy(mixed.boot_kernel_a, "20261112-r184");
    mixed.have_boot_kernel_b = 1;
    strcpy(mixed.boot_kernel_b, "20261112-r184");
    check(y4_grubenv_render(&mixed, block) == 0, "render mixed block");
    struct y4_slot_state parsed;
    memset(&parsed, 0, sizeof parsed);
    parse_block(block, &parsed);
    check(parsed.have_boot_kernel == 1 && parsed.have_boot_kernel_a == 1,
          "mixed keys round trip");
    check(!strcmp(parsed.boot_kernel, "6.6.89-cix-build-generic") &&
          !strcmp(parsed.boot_kernel_a, "20261112-r184"), "mixed values intact");
  }

  /* Oversized values are refused at parse time. Path-charset safety for
   * names that become FAT path components is enforced where they are used
   * (ota.c valid_name), not in the generic store. */
  {
    unsigned char big[Y4_GRUBENV_BYTES];
    memset(big, '#', sizeof big);
    int n = snprintf((char *)big, sizeof big,
                     "# GRUB Environment Block\n"
                     "# WARNING: Do not edit this file by tools other than grub-editenv!!!\n"
                     "boot_kernel_a=");
    memset(big + n, 'x', 300);
    big[n + 300] = '\n';
    struct y4_slot_state parsed2;
    memset(&parsed2, 0, sizeof parsed2);
    check(y4_grubenv_parse(big, &parsed2) == 0, "oversized block still parses");
    check(parsed2.have_boot_kernel_a == 0, "oversized value rejected");
  }

  /* Wrong signature and short blocks are refused. */
  {
    unsigned char raw[Y4_GRUBENV_BYTES];
    memset(raw, '#', sizeof raw);
    memcpy(raw, "NOT GRUB\n", 9);
    struct y4_slot_state parsed;
    check(y4_grubenv_parse(raw, &parsed) == -EINVAL, "bad signature refused");
  }

  /* File round trip through the atomic writer. */
  {
    const char *paths[] = {"/tmp/y4-grubenv-test-default", "/tmp/y4-grubenv-test-backup", NULL};
    unlink(paths[0]);
    unlink(paths[1]);
    struct y4_slot_state state2;
    memset(&state2, 0, sizeof state2);
    state2.have_default = 1; state2.default_entry = 0;
    state2.have_slot = 1; state2.slot[0] = 'A';
    state2.have_boot_kernel_a = 1;
    strcpy(state2.boot_kernel_a, "20261112-r184");
    state2.have_boot_kernel_b = 1;
    strcpy(state2.boot_kernel_b, "20261112-r184");
    check(y4_grubenv_write(paths, &state2) == 0, "atomic write");
    struct y4_slot_state read_back;
    check(y4_grubenv_read(paths[0], &read_back) == 0, "read back");
    check(!strcmp(read_back.boot_kernel_a, "20261112-r184"), "file round trip");
    check(y4_grubenv_read(paths[1], &read_back) == 0, "backup copy written");
    unlink(paths[0]);
    unlink(paths[1]);
  }

  if (failures) {
    fprintf(stderr, "test_grubenv: %d failure(s)\n", failures);
    return 1;
  }
  printf("test_grubenv: all checks passed\n");
  return 0;
}
